

/** @internal Escape HTML để render an toàn trong dashboard. */

export function escapeHtml(value: any) {

    return String(value)

        .replace(/&/g, '&amp;')

        .replace(/</g, '&lt;')

        .replace(/>/g, '&gt;')

        .replace(/"/g, '&quot;')

        .replace(/'/g, '&#39;');

}

